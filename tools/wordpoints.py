#!/usr/bin/env python3
"""Word points: how much an answer word's unfamiliarity adds to a puzzle's score.

known(w)   the share of Americans who know the word (freqdata/familiarity.json, from
           familiarity.py: Brysbaert et al. 2019 word prevalence, US respondents).
           An inflected form borrows its base word's score (yens <- yen), capped by
           how common that exact form is (wordfreq zipf), so rare forms of familiar
           words (YENS, RYES, OAFS) still count as somewhat unfamiliar. Words missing
           from the norms are estimated from frequency alone.
points(w)  under 60% known: 16; 60-75%: 8; 75-90%: 4; otherwise 0.

A puzzle's score = its spatial score (score.py / Solver.difficulty) + the points
of its answer words. Stars (Oct 25 2026):
    0-15 none (too easy)  16-30 1   31-50 2   51-70 3   71-85 4   86-100 5
    over 100: a special challenge, not for regular days

Running this file writes ../data/word_points.js (just the points per word, for the
Create page's difficulty), from the current valid list.
"""
import json, os

HERE = os.path.dirname(os.path.abspath(__file__))
_F = None
def _fam():
    global _F
    if _F is None:
        _F = json.load(open(os.path.join(HERE, 'freqdata', 'familiarity.json')))
    return _F

def _form_ceiling(z):                     # how common the exact form is -> familiarity ceiling
    pts = [(1.5, .68), (1.8, .78), (2.2, .90), (2.6, 1.0)]
    if z <= pts[0][0]:
        return pts[0][1]
    for (z0, k0), (z1, k1) in zip(pts, pts[1:]):
        if z <= z1:
            return k0 + (k1 - k0) * (z - z0) / (z1 - z0)
    return 1.0

def known(w):
    f = _fam().get(w, {})
    if f.get('known_us') is not None:
        k = f['known_us']
        if f.get('via') != w:                 # borrowed from a base word
            k = min(k, _form_ceiling(f.get('zipf', 0)))
        return k
    z = f.get('zipf', 0)                      # not in the norms at all
    return 0.95 if z >= 3.5 else 0.85 if z >= 3 else 0.7 if z >= 2.3 else 0.5

def points(w):
    k = known(w)
    return 16 if k < .60 else 8 if k < .75 else 4 if k < .90 else 0

STAR_BANDS = [(16, 30, 1), (31, 50, 2), (51, 70, 3), (71, 85, 4), (86, 100, 5)]
def stars(score):
    """1-5; 0 below 16 (too easy); 6 above 100 (a special challenge)."""
    if score > 100:
        return 6
    for lo, hi, s in STAR_BANDS:
        if lo <= score <= hi:
            return s
    return 0

words_of = lambda g: set(g) | {''.join(g[r][c] for r in range(4)) for c in range(4)}

def rescore(p):
    """A puzzle (pool or season entry) with difficulty = spatial + word points."""
    raw = dict(p.get('difficulty_raw', {}))
    spatial = raw.get('spatial', p['difficulty'])
    wp = {w: points(w) for w in words_of(p['solution'])}
    q = dict(p)
    q['difficulty'] = spatial + sum(wp.values())
    q['stars'] = stars(q['difficulty'])
    q['difficulty_raw'] = {**raw, 'spatial': spatial, 'word_points': sum(wp.values())}
    return q

if __name__ == '__main__':
    valid = open(os.path.join(HERE, 'valid4.txt')).read().split()
    pts = {w: points(w) for w in valid if points(w)}
    out = os.path.join(HERE, '..', 'data', 'word_points.js')
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write('// GENERATED by tools/wordpoints.py — do not edit by hand.\n'
                '// Difficulty points for less familiar words (16: under 60% of Americans know it,\n'
                '// 8: 60-75%, 4: 75-90%), derived from the word prevalence norms of Brysbaert,\n'
                '// Mandera, McCormick & Keuleers (2019). Words not listed score 0.\n'
                'const WORD_POINTS = ' + json.dumps(pts, separators=(',', ':')) + ';\n')
    from collections import Counter
    print(f'wrote data/word_points.js: {len(pts)} of {len(valid)} valid words score points;',
          dict(sorted(Counter(pts.values()).items())))
